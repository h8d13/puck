// symbols the real libalpm exports (and the consumers reference) that
// this read-path unit does not implement. pyalpm is linked BIND_NOW and
// go-alpm's cgo emits a C stub for every alpm_ function its package
// names, so all must resolve at load/link time or the consumer fails to
// start; these stubs complete the symbol table. none is on the read
// path. a call aborts naming itself, so the next C-ABI unit sees exactly
// which function a consumer reached for (PORTING.md follow-up grouping).
// alpm_list_add/alpm_list_free_inner are implemented in lib.rs instead.

macro_rules! stub {
	($name:ident) => {
		#[unsafe(no_mangle)]
		pub extern "C" fn $name() -> ! {
			eprintln!(
				"puck libalpm: {} is not in the read-path subset",
				stringify!($name)
			);
			std::process::abort()
		}
	};
}

