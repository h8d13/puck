#!/usr/bin/env python3
# alpm-core/src/signing/err_codes.rs from libgpg-error's src/err-codes.h.in
# (the gpg_strerror texts gpgme hands pacman), for the libgpg-error the C
# reference links. usage: scripts/gpg-err-codes.py <err-codes.h.in>
import re
import sys

rows = []
with open(sys.argv[1]) as f:
	for line in f:
		m = re.match(r"^(\d+)\t+(GPG_ERR_\w+)\t+(.*)$", line.rstrip("\n"))
		if m:
			rows.append((int(m.group(1)), m.group(3)))

print("// generated by scripts/gpg-err-codes.py from libgpg-error's")
print("// src/err-codes.h.in: gpg_strerror's text per error code, in the C")
print("// locale. do not edit")
print("pub(super) const ERR_CODES: &[(u32, &str)] = &[")
for code, text in rows:
	esc = text.replace("\\", "\\\\").replace('"', '\\"')
	print(f'\t({code}, "{esc}"),')
print("];")
